    private void initFormValidation() {
        javax.swing.event.DocumentListener listener = new javax.swing.event.DocumentListener() {
            @Override
            public void insertUpdate(javax.swing.event.DocumentEvent e) {
                updateConnectButtonState();
            }
            
            @Override
            public void removeUpdate(javax.swing.event.DocumentEvent e) {
                updateConnectButtonState();
            }
            
            @Override
            public void changedUpdate(javax.swing.event.DocumentEvent e) {
                updateConnectButtonState();
            }
        };
        
        urlTextField.getDocument().addDocumentListener(listener);
        userNameTextField.getDocument().addDocumentListener(listener);
        passwordField.getDocument().addDocumentListener(listener);
        
        updateConnectButtonState();
    }
    
    private void updateConnectButtonState() {
        String url = urlTextField.getText().trim();
        String user = userNameTextField.getText().trim();
        char[] password = passwordField.getPassword();
        
        boolean isFormValid = !url.isEmpty() && !user.isEmpty() && password.length > 0;
        connectButton.setEnabled(isFormValid);
        
        java.util.Arrays.fill(password, '\0');
    }

